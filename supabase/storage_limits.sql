-- ============================================================
-- ストレージのファイルサイズ上限を設定
-- ============================================================
-- storage.sql の後に実行してください（バケット作成後の追加設定）。
--
-- なぜ必要か:
--   出品フォームでは「最大300MB」と案内しているが、
--   Supabase Storage側で上限を設定しないと、悪意あるユーザーが
--   巨大なファイルをアップロードしてストレージ費用を膨らませられる。
--   アプリ側のチェックだけでなく、保管場所側でも制限をかけておく。
-- ============================================================

update storage.buckets
set file_size_limit = 314572800  -- 300MB（300 * 1024 * 1024）
where id = 'tool-files';

update storage.buckets
set file_size_limit = 10485760   -- 10MB（スクリーンショット用途には十分）
where id = 'tool-images';
