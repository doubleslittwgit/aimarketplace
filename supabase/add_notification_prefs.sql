-- ============================================================
-- profiles.notification_prefs
-- ============================================================
-- 通知の種類ごとのメール受信可否。空オブジェクト {} = 全種類オン（既定）。
-- キーに false を持つ種類だけがメール送信をスキップされる
-- （アプリ内通知は常に保存される。メールだけを止める仕組み）。
-- 重要な取引系の通知（審査結果・売上・購入完了等）はオフにできない
-- 設計にしているため、ここには「任意でオフにできる種類」だけが入る。
-- ============================================================

alter table public.profiles add column if not exists notification_prefs jsonb not null default '{}'::jsonb;
