/**
 * ツールのURL（slug）を作る。
 *
 * 【以前の問題】
 * 英数字以外をすべて削除する作りだったため、日本語名のツールでは
 * 何も残らず、「-72bcbb」のように先頭がハイフンだけのURLが
 * 生成されていた。これはURLとして正しく解決されず、商品ページを
 * 開こうとするとエラーページが表示されていた。
 * （「テキストリスト整理ツール」「重複ファイル検出・削除ツール」などが該当）
 *
 * 【対応】
 * 英数字部分が残らなかった場合は "tool" を代わりに使い、
 * 必ず「文字で始まるslug」になるようにしている。
 * 日本語をローマ字に変換する方法もあるが、変換の精度に依存し
 * 外部ライブラリも必要になるため、確実に壊れない方を選んだ。
 * （URLの読みやすさより、確実に開けることを優先する）
 */
export function slugify(input: string): string {
  const base = input
    .toLowerCase()
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/(^-|-$)/g, "")
    .slice(0, 40)
    // slice で末尾がハイフンになることがあるので、もう一度落とす
    .replace(/-+$/g, "");

  return base || "tool";
}
